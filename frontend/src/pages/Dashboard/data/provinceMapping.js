export const resolveGeoJSONProvinceName = (name) => {
  if (!name) return null;
  const upper = name.trim().toUpperCase();
  if (PROVINCE_NAME_MAP[upper]) {
    return PROVINCE_NAME_MAP[upper];
  }
  for (const key of Object.keys(PROVINCE_DISPLAY_NAMES)) {
    if (key.toUpperCase() === upper) return key;
  }
  return null;
};
